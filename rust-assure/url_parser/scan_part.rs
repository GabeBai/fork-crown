struct UrlKeyValue<'a> {
    key: &'a str,
    value: &'a str,
}

fn scan_part(input: &str, category: Category, delimiter1: char, delimiter2: char) -> Option<&str> {
    let mut chars = input.chars();
    while let Some(c) = chars.next() {
        if c == '\0' || c == delimiter1 || c == delimiter2 {
            return Some(&input[..input.len() - chars.as_str().len()]);
        }
        let char_index = c as usize;
        if CHAR_CAT[char_index] & category.bits() != 0 {
            continue;
        } else {
            return None;
        }
    }
    Some(input)
}

