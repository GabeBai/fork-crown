unsafe fn scan_part(start: *mut u8, category: Category, delimiter1: u8, delimiter2: u8) -> *mut u8 {
    let mut p = start;
    loop {
        if *p == 0 || *p == delimiter1 || *p == delimiter2 {
            return p;
        }
        if CHAR_CAT[*p as usize] & category as u16 != 0 {
            p = p.add(1);
        } else {
            return std::ptr::null_mut();
        }
    }
}